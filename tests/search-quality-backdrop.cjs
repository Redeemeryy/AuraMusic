const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const solid=color=>'data:image/svg+xml,'+encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40"><rect width="40" height="40" fill="${color}"/></svg>`);
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    for (const [width,height] of [[320,640],[347,754],[800,360]]) {
      const page=await browser.newPage({viewport:{width,height}}),errors=[];
      page.on('pageerror',e=>errors.push(e.message));
      await page.route('https://**',r=>r.abort());
      await page.goto(pathToFileURL(path.resolve('app/src/main/assets/web/index.html')).href);
      await page.evaluate(()=>switchView('search'));
      await page.waitForTimeout(350);
      const sources=await page.locator('#sourceTabs button').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {left:r.left,right:r.right,height:r.height};}));
      assert.equal(sources.length,6);
      assert.ok(sources.every(r=>r.left>=0&&r.right<=width&&r.height>=42),'all source buttons reachable without clipping');
      await page.locator('#searchInput').focus();
      assert.equal(await page.locator('#searchInput').evaluate(e=>getComputedStyle(e).outlineStyle),'none','focus belongs to the pill, not a square input');
      await page.locator('[data-source="wy"]').click();
      await page.waitForTimeout(350);
      assert.equal(await page.locator('#sourceTabs [aria-pressed="true"]').count(),1);
      assert.equal(await page.locator('#sourceTabs [aria-pressed="true"]').getAttribute('data-source'),'wy');
      assert.equal(await page.locator('#searchInput').inputValue(),'','source choice must not inject a query');
      await page.screenshot({path:`artifacts/search-new-${width}.png`});
      await page.evaluate(()=>{
        window.searchCalls=[]; window.searchReplies={};
        window.MusicAPI={initialized:true,search:(q,s)=>{searchCalls.push([q,s]);return new Promise(resolve=>searchReplies[q]=resolve);},searchPlaylists:async()=>({items:[]})};
      });
      await page.locator('#searchInput').fill('旧关键词'); await page.locator('#btnDoSearch').click();
      await page.locator('#searchInput').fill('新关键词'); await page.locator('#searchInput').press('Enter');
      await page.evaluate(()=>searchReplies['新关键词']({items:[{title:'新的结果',subtitle:'歌手',ref:{id:'2',providerId:'wy'}}]}));
      await page.waitForTimeout(80);
      await page.evaluate(()=>searchReplies['旧关键词']({items:[{title:'过期结果',subtitle:'歌手',ref:{id:'1',providerId:'wy'}}]}));
      await page.waitForTimeout(80);
      assert.match(await page.locator('#searchResultsList').textContent(),/新的结果/);
      assert.doesNotMatch(await page.locator('#searchResultsList').textContent(),/过期结果/);
      await page.locator('#btnClearSearch').click();
      assert.ok(await page.locator('#hotSearchSection').isVisible());
      await page.evaluate(()=>openFullPlayer());
      await page.locator('#fullQualityPill').click();
      await page.waitForTimeout(400);
      assert.equal(await page.locator('.quality-check-icon:visible').count(),1,'only the current quality gets a checkmark');
      const sheet=await page.locator('#qualityModalContent').boundingBox();
      assert.ok(sheet.x>=0&&sheet.x+sheet.width<=width+1&&sheet.y>=0&&sheet.y+sheet.height<=height+1,'quality sheet stays in viewport');
      const last=page.locator('.quality-picker-option').last();await last.scrollIntoViewIfNeeded();
      const r=await last.boundingBox();assert.ok(r.y>=0&&r.y+r.height<=height,'last quality reachable');
      await page.screenshot({path:`artifacts/quality-new-${width}.png`});
      assert.equal(await page.evaluate(()=>handleBackPress()),true);
      assert.equal(await page.locator('#qualityModalOverlay').getAttribute('aria-hidden'),'true');
      await page.waitForTimeout(350);
      await page.locator('#fullQualityPill').click();await page.locator('[data-quality="128k"]').click();
      assert.equal(await page.evaluate(()=>localStorage.getItem('jelly_preferred_quality')),'128k');
      assert.deepEqual(errors,[]);
      await page.close(); console.log(`PASS search sources, stale results, quality layout/select/back ${width}x${height}`);
    }
    const page=await browser.newPage({viewport:{width:347,height:754}});
    await page.route('https://**',r=>r.abort());
    await page.goto(pathToFileURL(path.resolve('app/src/main/assets/web/index.html')).href);
    await page.evaluate(()=>openFullPlayer());
    const black=solid('#15151a'),pink=solid('#f4a5c7'),blue=solid('#74a9df');
    await page.evaluate(url=>AuraBackdrop.setArtwork(url),black);
    await page.waitForFunction(url=>document.querySelector('.player-artwork-backdrop').dataset.artwork===url,black);
    await page.evaluate(url=>AuraBackdrop.setArtwork(url),pink);
    await page.waitForTimeout(200);
    const mid=await page.locator('.player-artwork-layer').last().evaluate(e=>Number(getComputedStyle(e).opacity));
    assert.ok(mid>0&&mid<1,'artwork genuinely interpolates while old layer stays visible');
    assert.equal(await page.locator('.player-artwork-layer').count(),2);
    await page.evaluate(url=>AuraBackdrop.setArtwork(url),blue);
    await page.waitForFunction(url=>document.querySelector('.player-artwork-backdrop').dataset.artwork===url,blue);
    assert.equal(await page.locator('.player-artwork-layer').count(),1,'superseded layers cleaned up');
    await page.evaluate(url=>{document.documentElement.classList.add('reduce-motion');return AuraBackdrop.setArtwork(url);},black);
    assert.equal(await page.locator('.player-artwork-backdrop').getAttribute('data-artwork'),black);
    assert.equal(await page.locator('.player-artwork-backdrop').evaluate(e=>e.getAnimations({subtree:true}).length),0);
    await page.evaluate(url=>AuraBackdrop.setArtwork('https://invalid.test/cover',url),pink);
    assert.equal(await page.locator('.player-artwork-backdrop').getAttribute('data-artwork'),pink,'failed cover uses decoded fallback');
    await page.close();console.log('PASS backdrop crossfade, rapid-track latest winner, reduced motion and failed-image fallback');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
